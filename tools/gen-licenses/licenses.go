// Package main generates web/public/licenses.txt, the open-source licences
// page the till's About screen links to (ut-docs#6402). It lists every module
// go.mod requires (direct and indirect, first-party replaced modules aside)
// with the licence files found in that module's source.
//
// Offline by design: licence text is read from the module cache that the
// build itself already filled, so CI needs no network for this. Only a module
// missing from the cache triggers `go mod download` (which `go build` would
// need anyway).
//
//	go run ./tools/gen-licenses            # rewrite web/public/licenses.txt
//	go run ./tools/gen-licenses -check     # exit 1 when the file is stale
package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// firstPartyPrefix: modules of this repository (replaced to local paths) are
// covered by the product's own licence, not listed as third-party.
const firstPartyPrefix = "github.com/universaltill/universal-till"

// Module is one go.mod requirement.
type Module struct {
	Path    string
	Version string
}

// LicenceFile is one licence/notice file found in a module's root.
type LicenceFile struct {
	Name string
	Text string
}

var licenceName = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|unlicen[cs]e|patents)([._-].*)?$`)

// IsLicenceFileName reports whether name looks like a licence or notice file.
func IsLicenceFileName(name string) bool {
	return !strings.HasSuffix(name, ".go") && licenceName.MatchString(name)
}

// ParseRequires returns every requirement in a go.mod (require blocks and
// single-line requires), first-party modules excluded, sorted by path. The
// "// indirect" marker does not matter: indirect modules ship in the binary too.
func ParseRequires(gomod string) []Module {
	var mods []Module
	inBlock := false
	sc := bufio.NewScanner(strings.NewReader(gomod))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if i := strings.Index(line, "//"); i >= 0 {
			line = strings.TrimSpace(line[:i])
		}
		switch {
		case line == "":
			continue
		case line == "require (":
			inBlock = true
			continue
		case inBlock && line == ")":
			inBlock = false
			continue
		}
		var spec string
		switch {
		case inBlock:
			spec = line
		case strings.HasPrefix(line, "require "):
			spec = strings.TrimSpace(strings.TrimPrefix(line, "require "))
		default:
			continue
		}
		f := strings.Fields(spec)
		if len(f) != 2 || strings.HasPrefix(f[0], firstPartyPrefix) {
			continue
		}
		mods = append(mods, Module{Path: f[0], Version: f[1]})
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })
	return mods
}

// Render builds the licences text. read returns a module's licence files; a
// module with none is an error (a page that silently omits a dependency's
// licence is worse than a failed build).
func Render(mods []Module, read func(Module) ([]LicenceFile, error)) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "Open-source licences used by Universal Till\n")
	fmt.Fprintf(&b, "Generated by tools/gen-licenses from go.mod and the maintained component list; do not edit by hand (make licenses).\n")
	fmt.Fprintf(&b, "Go modules listed: %d\n", len(mods))
	var missing []string
	for _, m := range mods {
		files, err := read(m)
		if err != nil || len(files) == 0 {
			missing = append(missing, m.Path+"@"+m.Version)
			continue
		}
		b.WriteString("\n" + strings.Repeat("=", 72) + "\n")
		fmt.Fprintf(&b, "%s %s\n", m.Path, m.Version)
		for _, f := range files {
			fmt.Fprintf(&b, "%s\n%s [%s]\n%s\n", strings.Repeat("-", 72), m.Path, f.Name, strings.Repeat("-", 72))
			b.WriteString(strings.TrimSpace(strings.ReplaceAll(f.Text, "\r\n", "\n")) + "\n")
		}
	}
	if len(missing) > 0 {
		return "", fmt.Errorf("no licence file found for: %s", strings.Join(missing, ", "))
	}
	return b.String(), nil
}

// ListedModules returns the modules a generated file lists, by header lines.
func ListedModules(generated string) map[string]string {
	out := map[string]string{}
	lines := strings.Split(generated, "\n")
	sep := strings.Repeat("=", 72)
	for i := 0; i+1 < len(lines); i++ {
		if lines[i] == sep {
			if f := strings.Fields(lines[i+1]); len(f) == 2 {
				out[f[0]] = f[1]
			}
		}
	}
	return out
}

// MissingFrom returns the go.mod modules (path@version) the generated file
// does not list at that exact version.
func MissingFrom(mods []Module, generated string) []string {
	listed := ListedModules(generated)
	var missing []string
	for _, m := range mods {
		if listed[m.Path] != m.Version {
			missing = append(missing, m.Path+"@"+m.Version)
		}
	}
	return missing
}

// readFromDir reads the licence files in dir (module root, not recursive).
func readFromDir(dir string) ([]LicenceFile, error) {
	ents, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var out []LicenceFile
	for _, e := range ents {
		if e.IsDir() || !IsLicenceFileName(e.Name()) {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		out = append(out, LicenceFile{Name: e.Name(), Text: string(b)})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

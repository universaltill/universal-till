//go:build ignore

// Generates ios/UniversalTillTests/Fixtures/pin_vector.json: certificates of the
// kinds the reader app must and must not pin, with the pin Go's lantls.PinOf
// makes for each, plus a pairing-code vector (same formula as
// derivedVerificationCode in internal/pages/pairing_api.go). Run once and commit
// the output; the Swift tests read it:
//
//	go run ios/scripts/gen-pin-vector.go > ios/UniversalTillTests/Fixtures/pin_vector.json
package main

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/rsa"
	"crypto/sha256"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/base64"
	"encoding/binary"
	"encoding/json"
	"fmt"
	"math/big"
	"os"
	"time"

	"github.com/universaltill/universal-till/internal/lantls"
)

func cert(pub, priv any) *x509.Certificate {
	tpl := &x509.Certificate{
		SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: "ut-pin-vector"},
		NotBefore: time.Unix(1_700_000_000, 0), NotAfter: time.Unix(4_000_000_000, 0),
	}
	der, err := x509.CreateCertificate(rand.Reader, tpl, tpl, pub, priv)
	if err != nil {
		panic(err)
	}
	c, err := x509.ParseCertificate(der)
	if err != nil {
		panic(err)
	}
	return c
}

func main() {
	p256, _ := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	p384, _ := ecdsa.GenerateKey(elliptic.P384(), rand.Reader)
	rsaKey, _ := rsa.GenerateKey(rand.Reader, 2048)
	c256 := cert(&p256.PublicKey, p256)
	c384 := cert(&p384.PublicKey, p384)
	cRSA := cert(&rsaKey.PublicKey, rsaKey)
	b64 := base64.StdEncoding.EncodeToString
	commitment := "5e884898da28047151d0e56f8dc6292773603d0d6aabbdd62a11ef721d1542d8"
	tillID := "main-till-fixture"
	sum := sha256.Sum256([]byte(commitment + tillID + lantls.PinOf(c256)))
	out := map[string]any{
		"_comment":  "Generated by ios/scripts/gen-pin-vector.go; pin = lantls.PinOf (hex sha256 of the SPKI).",
		"p256_cert": b64(c256.Raw), "p256_pin": lantls.PinOf(c256),
		"p384_cert": b64(c384.Raw), "p384_pin": lantls.PinOf(c384),
		"rsa_cert": b64(cRSA.Raw), "rsa_pin": lantls.PinOf(cRSA),
		"code": map[string]string{
			"commitment": commitment, "till_id": tillID, "pin": lantls.PinOf(c256),
			"code": fmt.Sprintf("%06d", binary.BigEndian.Uint32(sum[:4])%1000000),
		},
	}
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	_ = enc.Encode(out)
}

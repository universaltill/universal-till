// ADR-0200 (ut-docs#6559): the till's change-event outbox.

func newChangeEventsTestDB(t *testing.T) (*db.DB, *ChangeEventsRepo) {
	t.Helper()
	d, err := db.Open(testsupport.MigratedDBFile(t, "change_events.db"))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = d.Close() })
	return d, NewChangeEventsRepo(d.DB)
}

func allowChangeEvents(t *testing.T) {
	t.Helper()
	SetChangeEventPolicy(func(func(string) string) bool { return true })
	t.Cleanup(func() { SetChangeEventPolicy(nil) })
}

func TestChangeEvents_AppendListAckRoundTrip(t *testing.T) {
	_, repo := newChangeEventsTestDB(t)
	ctx := context.Background()
	at := time.Now().UTC().Truncate(time.Second)
	ev := ChangeEvent{Kind: ChangeKindPlugin, PluginID: "ut-plugin-payment-stripe", Action: ChangeActionInstall, To: "1.2.0", At: at}
	if err := repo.Append(ctx, nil, ev); err != nil {
		t.Fatalf("Append: %v", err)
	}
	got, err := repo.ListPending(ctx, ChangeEventBatch)
	if err != nil || len(got) != 1 {
		t.Fatalf("ListPending = %v, %v; want one event", got, err)
	}
	if got[0].ID == "" || len(got[0].ID) != 32 {
		t.Errorf("id %q: want 32 hex chars generated by the repo", got[0].ID)
	}
	if got[0].PluginID != ev.PluginID || got[0].Action != "install" || got[0].To != "1.2.0" || got[0].From != "" || !got[0].At.Equal(at) {
		t.Errorf("round trip lost fields: %+v", got[0])
	}
	if err := repo.Ack(ctx, []string{got[0].ID}); err != nil {
		t.Fatalf("Ack: %v", err)
	}
	if n, _ := repo.Count(ctx); n != 0 {
		t.Errorf("after Ack count = %d, want 0", n)
	}
}

func TestChangeEvents_BoundedAt200KeepsNewest(t *testing.T) {
	_, repo := newChangeEventsTestDB(t)
	ctx := context.Background()
	for i := 0; i < 300; i++ {
		ev := ChangeEvent{Kind: ChangeKindPlugin, PluginID: "p" + fmt.Sprint(i), Action: ChangeActionInstall, To: "1.0.0", At: time.Now().UTC()}
		if err := repo.Append(ctx, nil, ev); err != nil {
			t.Fatalf("Append %d: %v", i, err)
		}
	}
	if n, _ := repo.Count(ctx); n != ChangeEventCap {
		t.Fatalf("count = %d, want cap %d", n, ChangeEventCap)
	}
	all, _ := repo.ListPending(ctx, 1000)
	if all[0].PluginID != "p100" || all[len(all)-1].PluginID != "p299" {
		t.Errorf("kept %s..%s, want the newest p100..p299 (oldest dropped)", all[0].PluginID, all[len(all)-1].PluginID)
	}
}

func TestChangeEvents_ListPendingCapsBatchAndIsOldestFirst(t *testing.T) {
	_, repo := newChangeEventsTestDB(t)
	ctx := context.Background()
	for i := 0; i < 120; i++ {
		_ = repo.Append(ctx, nil, ChangeEvent{Kind: ChangeKindPlugin, PluginID: "p" + fmt.Sprint(i), Action: ChangeActionUpdate, From: "1.0.0", To: "1.1.0", At: time.Now().UTC()})
	}
	got, err := repo.ListPending(ctx, 50)
	if err != nil || len(got) != 50 {
		t.Fatalf("batch = %d, %v; want 50", len(got), err)
	}
	if got[0].PluginID != "p0" || got[49].PluginID != "p49" {
		t.Errorf("order %s..%s, want oldest first p0..p49", got[0].PluginID, got[49].PluginID)
	}
}

func TestChangeEvents_RejectsInvalidShapes(t *testing.T) {
	_, repo := newChangeEventsTestDB(t)
	ctx := context.Background()
	now := time.Now().UTC()
	bad := map[string]ChangeEvent{
		"unknown kind":         {Kind: "sale", At: now},
		"plugin without id":    {Kind: ChangeKindPlugin, Action: ChangeActionInstall, At: now},
		"plugin uppercase id":  {Kind: ChangeKindPlugin, PluginID: "Com.X", Action: ChangeActionInstall, At: now},
		"unknown action":       {Kind: ChangeKindPlugin, PluginID: "p", Action: "explode", At: now},
		"version with action":  {Kind: ChangeKindVersion, Action: "install", From: "1.0.0", To: "1.1.0", At: now},
		"version too long":     {Kind: ChangeKindVersion, From: "1.0.0", To: strings.Repeat("1", 33), At: now},
		"version bad charset":  {Kind: ChangeKindVersion, From: "1.0.0", To: "1.1 0", At: now},
		"zero time":            {Kind: ChangeKindVersion, From: "1.0.0", To: "1.1.0"},
		"plugin id too long":   {Kind: ChangeKindPlugin, PluginID: strings.Repeat("a", 65), Action: ChangeActionRemove, At: now},
		"plugin with path-ish": {Kind: ChangeKindPlugin, PluginID: "../etc", Action: ChangeActionRemove, At: now},
	}
	for name, ev := range bad {
		if err := repo.Append(ctx, nil, ev); err == nil {
			t.Errorf("%s: Append accepted an invalid event", name)
		}
	}
	if n, _ := repo.Count(ctx); n != 0 {
		t.Errorf("invalid events stored: %d", n)
	}
}

func TestChangeEvents_NoPolicyRecordsNothing(t *testing.T) {
	_, repo := newChangeEventsTestDB(t)
	ctx := context.Background()
	SetChangeEventPolicy(nil)
	recordPluginEvent(ctx, repo.db, "ut-plugin-x", ChangeActionInstall, "", "1.0.0")
	repo.RecordVersionChange(ctx, repo.db, "0.36.0", "0.37.0")
	if n, _ := repo.Count(ctx); n != 0 {
		t.Fatalf("no policy wired but %d events recorded", n)
	}
}

func TestChangeEvents_PolicyReadsSettingsThroughTheSameTx(t *testing.T) {
	d, repo := newChangeEventsTestDB(t)
	ctx := context.Background()
	sr := NewSettingsRepo(d.DB)
	if err := sr.Set(ctx, "registration.stopped", "true"); err != nil {
		t.Fatal(err)
	}
	SetChangeEventPolicy(func(get func(string) string) bool { return get("registration.stopped") != "true" })
	t.Cleanup(func() { SetChangeEventPolicy(nil) })
	repo.RecordVersionChange(ctx, repo.db, "0.36.0", "0.37.0")
	if n, _ := repo.Count(ctx); n != 0 {
		t.Fatalf("policy said no (stopped) but %d recorded", n)
	}
	if err := sr.Set(ctx, "registration.stopped", "false"); err != nil {
		t.Fatal(err)
	}
	repo.RecordVersionChange(ctx, repo.db, "0.36.0", "0.37.0")
	if n, _ := repo.Count(ctx); n != 1 {
		t.Fatalf("policy said yes but count = %d", n)
	}
}

func TestPluginRepo_RecordsInstallUpdateRemoveOncePerChange(t *testing.T) {
	allowChangeEvents(t)
	d, repo := newPluginLifecycleTestDB(t)
	ctx := context.Background()
	events := NewChangeEventsRepo(d.DB)
	upsert := func(version, trust string) {
		t.Helper()
		seedCatalogForManifest(t, d, "ut-plugin-x", version)
		tx, _ := d.DB.BeginTx(ctx, nil)
		now := time.Now().UTC()
		if err := repo.UpsertPluginManifest(ctx, tx, ManifestRow{ID: "ut-plugin-x", Name: "X", Version: version, InstallState: "installed", TrustLevel: trust, InstalledAt: now, UpdatedAt: now}); err != nil {
			t.Fatal(err)
		}
		if err := tx.Commit(); err != nil {
			t.Fatal(err)
		}
	}
	upsert("1.0.0", "trusted") // install
	upsert("1.0.0", "trusted") // same version: nothing
	upsert("1.1.0", "trusted") // update
	tx, _ := d.DB.BeginTx(ctx, nil)
	if err := repo.DeletePlugin(ctx, tx, "ut-plugin-x"); err != nil {
		t.Fatal(err)
	}
	_ = tx.Commit()
	got, _ := events.ListPending(ctx, 50)
	want := []string{"install::1.0.0", "update:1.0.0:1.1.0", "remove:1.1.0:"}
	if len(got) != len(want) {
		t.Fatalf("events = %+v, want %v", got, want)
	}
	for i, w := range want {
		if s := got[i].Action + ":" + got[i].From + ":" + got[i].To; s != w {
			t.Errorf("event %d = %s, want %s", i, s, w)
		}
	}
}


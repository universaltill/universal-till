func seedCatalogForManifest(t *testing.T, d *db.DB, id, version string) {
	t.Helper()
	err := NewPluginRepo(d.DB).EnsureCatalogEntry(context.Background(), nil, CatalogUpsertRow{
		ID: id, Version: version, Name: "X", Runtime: "wasm", Entrypoint: "x.wasm", PublishedAt: time.Now().UTC().Format(time.RFC3339),
	})
	if err != nil {
		t.Fatalf("seed catalog: %v", err)
	}
}
